-- Source only: not applied. Cloud opt-in and the session leak guard are enforced before the browser sends a row.
create table public.rulings (
  event_id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  project_key text not null check (char_length(project_key) between 1 and 256),
  finding_id text not null check (char_length(finding_id) between 1 and 1024),
  content_hash text not null check (content_hash ~ '^[0-9a-f]{64}$'),
  value_tag text not null check (value_tag ~ '^[0-9a-f]{64}$'),
  decision text not null check (decision in ('dismiss_approved', 'real', 'skip')),
  reason_code text not null check (char_length(reason_code) between 1 and 100),
  note text not null default '' check (char_length(note) <= 500),
  is_audit boolean not null default false,
  audit_cohort_id text check (audit_cohort_id is null or char_length(audit_cohort_id) between 1 and 512),
  created_at timestamptz not null default now(),
  check (not is_audit or audit_cohort_id is not null)
);
create index rulings_owner_project_latest on public.rulings (user_id, project_key, finding_id, created_at, event_id);
alter table public.rulings enable row level security;
revoke all on public.rulings from public, anon, authenticated;
grant select on public.rulings to authenticated;
grant insert (user_id, project_key, finding_id, content_hash, value_tag, decision, reason_code, note, is_audit, audit_cohort_id)
  on public.rulings to authenticated;
-- Client inserts cannot forge event_id/created_at; ordering metadata is generated by the database.
grant usage, select on sequence public.rulings_event_id_seq to authenticated;
-- Append-only for all end-user roles. No UPDATE/DELETE policies exist.
revoke update, delete, truncate, references, trigger on public.rulings from public, anon, authenticated;
create policy rulings_owner_select on public.rulings for select to authenticated using (user_id = (select auth.uid()));
create policy rulings_owner_insert on public.rulings for insert to authenticated with check (user_id = (select auth.uid()));
